# ═══════════════════════════════════════════════════════════════════════════════
# customers.riskmandate.ai — Gen__Meter
# Writes assets/site-config.js from data/meter.json and data/storyboards.json
# (the meter's config, given as window.SG_METER_CONFIG because this site's
# content security policy runs no inline script, and the storyboard viewer's
# storage key), and the prices table in every page that carries a
# <!-- rm-customers:prices:start --> block. `--check` fails on drift.
# Usage: python3 admin/build/gen_meter.py [--check]
# ═══════════════════════════════════════════════════════════════════════════════

import html
import json
import sys

from chrome import ROOT, METER, KIT
from pages  import Site__Pages


CONFIG_FILE = ROOT / 'assets' / 'site-config.js'


class Gen__Meter:

    def __init__(self, check=False):
        self.check = check
        self.pages = Site__Pages()
        self.validate()

    def validate(self):
        kinds    = [k['kind'] for k in METER['kinds']]
        problems = []
        if len(set(kinds)) != len(kinds):
            problems.append('a kind is listed twice')
        for prefix, kind in METER['paths']:
            if kind not in kinds:
                problems.append(f'path rule {prefix} names an unknown kind {kind}')
        if METER['config']['start'] != 5000:
            problems.append('every reader starts with £50.00: config.start is 5000 pence')
        if 'free' not in kinds or next(k for k in METER['kinds'] if k['kind'] == 'free')['price'] != 0:
            problems.append('the free kind costs nothing')
        if problems:
            raise SystemExit('data/meter.json is invalid:\n  ' + '\n  '.join(problems))

    def config(self):
        cfg = dict(METER['config'])
        cfg['prices'] = {k['kind']: k['price'] for k in METER['kinds']}
        return cfg

    def config_js(self):
        return '\n'.join(['// ── site-config.js — generated by admin/build/gen_meter.py from data/meter.json and data/storyboards.json; do not edit ──',
                          '//',
                          '// The reading meter reads window.SG_METER_CONFIG when the page has no inline config block, and this site runs no',
                          '// inline script. The storyboard viewer keeps its preferences under the key in window.StoryboardPrefsKey.',
                          '',
                          f'window.SG_METER_CONFIG = {json.dumps(self.config(), ensure_ascii=False, sort_keys=True)}',
                          f'window.StoryboardPrefsKey = {json.dumps(KIT["prefs_key"])}',
                          ''])

    def money(self, pence):
        return 'nothing' if pence == 0 else f'{pence}p' if pence < 100 else f'£{pence / 100:.2f}'

    def prices_html(self):
        start = METER['config']['start']
        rows  = []
        for k in METER['kinds']:
            reads = '' if k['price'] == 0 else f'{start // k["price"]:,}'
            rows.append(f'      <tr><td><code>{k["kind"]}</code></td><td>{html.escape(k["what"])}</td><td>{self.money(k["price"])}</td><td>{reads}</td></tr>')
        return '\n'.join(['  <table class="prices" data-generated-from="data/meter.json">'                                                             ,
                          '    <thead><tr><th>Kind</th><th>Which pages</th><th>Read to the end</th><th>Read to the end, on £50.00</th></tr></thead>',
                          '    <tbody>'                                                                                                             ,
                          *rows                                                                                                                     ,
                          '    </tbody>'                                                                                                            ,
                          '  </table>'                                                                                                              ])

    def run(self):
        changed = []
        if self.pages.write_if_changed(CONFIG_FILE, self.config_js(), self.check):
            changed.append('assets/site-config.js')
        for path in self.pages.html_files():
            text = path.read_text(encoding='utf-8')
            if not self.pages.has_block(text, 'prices'):
                continue
            text, _ = self.pages.replace_block(text, 'prices', self.prices_html())
            if self.pages.write_if_changed(path, text, self.check):
                changed.append(path.relative_to(ROOT).as_posix())
        return changed


if __name__ == '__main__':
    check   = '--check' in sys.argv
    changed = Gen__Meter(check=check).run()
    verb    = 'stale' if check else 'updated'
    for name in changed:
        print(f'  meter {verb}: {name}')
    if check and changed:
        print(f'gen_meter --check: {len(changed)} file(s) out of date; run python3 admin/build/gen_meter.py')
        sys.exit(1)
    print(f'gen_meter: {len(changed)} file(s) {verb}')
